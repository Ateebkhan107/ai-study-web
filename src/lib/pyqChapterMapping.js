const NORMALIZED_TO_CANONICAL = new Map();

function normalizeKey(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[–—]/g, "-")
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

for (const chapters of Object.values(TEST_PAGE_CHAPTERS)) {
  for (const chapter of chapters) {
    NORMALIZED_TO_CANONICAL.set(normalizeKey(chapter), chapter);
  }
}

for (const [canonical, aliases] of Object.entries(CHAPTER_ALIASES)) {
  NORMALIZED_TO_CANONICAL.set(normalizeKey(canonical), canonical);
  for (const alias of aliases) {
    NORMALIZED_TO_CANONICAL.set(normalizeKey(alias), canonical);
  }
}

export function normalizeChapterName(chapter) {
  return NORMALIZED_TO_CANONICAL.get(normalizeKey(chapter)) || chapter || "";
}

export function getSubjectTargets(subject) {
  const value = String(subject || "").trim();
  return SUBJECT_ALIASES[value] || [value];
}

export function getCanonicalSubject(subject) {
  return subject === "Mathematics" ? "Maths" : subject;
}

export function getCanonicalChaptersForSubject(subject) {
  return TEST_PAGE_CHAPTERS[getCanonicalSubject(subject)] || [];
}

export function getChapterTargets(chapter) {
  const canonical = normalizeChapterName(chapter);
  const targets = new Set([chapter, canonical].filter(Boolean));
  for (const alias of CHAPTER_ALIASES[canonical] || []) {
    targets.add(alias);
  }
  for (const legacyBroadChapter of LEGACY_BROAD_CHAPTER_TARGETS[canonical] || []) {
    targets.add(legacyBroadChapter);
  }
  return [...targets];
}
